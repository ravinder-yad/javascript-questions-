let arr = [10, 20, 30, 40];

// length
console.log(arr.length); 
// 4

// push
arr.push(50, 60);
console.log(arr);
// [10, 20, 30, 40, 50, 60]


// pop
arr.pop()
console.log(arr);
// [10, 20, 30, 40, 50]

// shift
arr.shift();
console.log(arr);
// [20, 30, 40, 50]

// unshift
arr.unshift(0, 5);
console.log(arr);
// [0, 5, 20, 30, 40, 50]

